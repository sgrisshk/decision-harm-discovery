@pytest.mark.skipif(not TRAVEL_DATASET.exists(), reason="delivered analytical dataset not present")
class TestSafety:
    @pytest.mark.parametrize(
        "conditions,expected_k,label",
        [
            (T01_COUNTERFACTUAL, 1, "T01-counterfactual"),
            (T02_COUNTERFACTUAL, 1, "T02-counterfactual"),
            (T03_REAL_CAND014, 2, "T03-real-CAND014"),
            (T04_REAL_CAND007, 3, "T04-real-CAND007"),
            (T04_REAL_CAND015, 2, "T04-real-CAND015"),
            (T05_COUNTERFACTUAL, 1, "T05-counterfactual"),
        ],
    )
    def test_all_5_traps_g16_wiring_correct(
        self, conditions: list[dict[str, Any]], expected_k: int, label: str
    ) -> None:
        assert len(conditions) == expected_k
        result = _run_one(
            TRAVEL_DATASET,
            conditions,
            primary_outcome(),
            TRAVEL_DATASET_VERSION,
            TRAVEL_OUTCOME_VERSION,
            label,
        )
        gate_results = result.report.gate_results
        g16 = next(g for g in gate_results if g.gate_id is GateId.COMPOSITION_SAFETY)
        if expected_k <= 1:
            assert g16.satisfied is True
            assert g16.outcome is GateOutcome.PASS
        else:
            assert g16.outcome in (GateOutcome.PASS, GateOutcome.FAIL)
            if not g16.satisfied:
                level = result.report.evidence_level
                assert level is None or LEVEL_ORDER.index(level) <= LEVEL_ORDER.index(
                    EvidenceLevel.PREDICTIVE
                )

    def test_p01_true_pattern_g16_executes_and_caps_consistently(self) -> None:
        result = _run_one(
            TRAVEL_DATASET,
            P01_TRUE_PATTERN,
            primary_outcome(),
            TRAVEL_DATASET_VERSION,
            TRAVEL_OUTCOME_VERSION,
            "P01-true-pattern",
        )
        gate_results = result.report.gate_results
        g16 = next(g for g in gate_results if g.gate_id is GateId.COMPOSITION_SAFETY)
        assert g16.outcome in (GateOutcome.PASS, GateOutcome.FAIL)
        if not g16.satisfied:
            level = result.report.evidence_level
            assert level is None or LEVEL_ORDER.index(level) <= LEVEL_ORDER.index(
                EvidenceLevel.PREDICTIVE
            )

    @pytest.mark.skipif(not B2B_DATASET.exists(), reason="b2b_sales analytical dataset not present")
    @pytest.mark.parametrize(
        "conditions,label", [(B2B_CAND001, "b2b-CAND001"), (B2B_CAND009, "b2b-CAND009")]
    )
    def test_second_domain_b2b_sales_g16_wiring_correct(
        self, conditions: list[dict[str, Any]], label: str
    ) -> None:
        """`TASK-070`'s own multi-domain precedent: `G16` must not be a travel-specific mechanism
        -- it is computed entirely from the candidate's own condition tuple and the frame, with
        no dataset-specific logic anywhere (confirmed structurally by the diff in this task's own
        report; confirmed behaviorally here on a real second domain).
        """
        manifest = json.loads((B2B_DATASET / "manifest.json").read_text(encoding="utf-8"))
        outcome, outcome_version = outcome_definition_from_manifest(manifest, B2B_DATASET)
        result = _run_one(
            B2B_DATASET, conditions, outcome, manifest["dataset_version"], outcome_version, label
        )
        gate_results = result.report.gate_results
        g16 = next(g for g in gate_results if g.gate_id is GateId.COMPOSITION_SAFETY)
        assert g16.outcome in (GateOutcome.PASS, GateOutcome.FAIL)
        assert g16.satisfied is False  # both b2b conditions above are k=2 compound
        level = result.report.evidence_level
        predictive_rank = LEVEL_ORDER.index(EvidenceLevel.PREDICTIVE)
        assert level is None or LEVEL_ORDER.index(level) <= predictive_rank


