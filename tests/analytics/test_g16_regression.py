def _confound_like_atoms(atoms: list[dict[str, Any]]) -> list[dict[str, Any]]:
    target = CompositionAtomClassification.CONFOUND_LIKE.value
    return [atom for atom in atoms if atom["classification"] == target]


@pytest.mark.skipif(not TRAVEL_DATASET.exists(), reason="delivered analytical dataset not present")
class TestDiagnostic:
    def test_p01_true_patterns_own_atoms_are_not_labeled_confound_like(self) -> None:
        """`P01`'s three atoms (`supplier`, `discount_rate`, `booking_lead_days`) are, by this
        pattern's own construction in `synthetic_benchmark.py`, jointly defining one true causal
        rule -- none is a confound of the others. `indeterminate` is the correct, expected
        outcome for all three (per `ADR-077`/`078`, this design never *asserts* "no confound" --
        it only ever withholds the positive `confound_like` claim). `confound_like` here would be
        a diagnostic finding worth investigating, not a safety failure.
        """
        result = _run_one(
            TRAVEL_DATASET,
            P01_TRUE_PATTERN,
            primary_outcome(),
            TRAVEL_DATASET_VERSION,
            TRAVEL_OUTCOME_VERSION,
            "P01-diagnostic",
        )
        atoms = result.diagnostics["composition_safety_atoms"]
        assert len(atoms) == 3
        offenders = _confound_like_atoms(atoms)
        assert offenders == [], f"P01's own atoms wrongly classified confound_like: {offenders}"

    def test_t04_real_cand007_structural_exclusion_not_labeled_confound_like(self) -> None:
        """`CAND-007` (`T04`, `k=3`) is `TASK-075`'s own "correct, structurally-exclusion-based
        handling" case -- a genuine `P06` recovery whose own condition features happen to equal
        `T04`'s true confounders, so `G02`'s circularity guard (not `G06`'s coverage floor)
        excludes them. `G16`'s own leave-one-out check has no such circularity concern (it never
        adjusts a candidate for its own condition), so this only asserts the diagnostic
        expectation that a genuine recovery's own atoms are not spuriously flagged
        confound_like -- again, `indeterminate` either way caps identically and would not be a
        safety failure.
        """
        result = _run_one(
            TRAVEL_DATASET,
            T04_REAL_CAND007,
            primary_outcome(),
            TRAVEL_DATASET_VERSION,
            TRAVEL_OUTCOME_VERSION,
            "T04-CAND007-diagnostic",
        )
        atoms = result.diagnostics["composition_safety_atoms"]
        assert len(atoms) == 3
        offenders = _confound_like_atoms(atoms)
        assert offenders == [], (
            f"CAND-007's own atoms wrongly classified confound_like: {offenders}"
        )
