def _parse_condition_token(token: str) -> dict[str, Any]:
    feature, operator, value = token.split(" ", 2)
    try:
        coerced: object = float(value) if "." in value else int(value)
    except ValueError:
        coerced = {"True": True, "False": False}.get(value, value)
    return {"feature": feature, "operator": operator, "value": coerced}


def _trap_conditions(
    trap_id: str, *, counterfactual: bool, label_prefix: str | None = None
) -> list[dict[str, Any]]:
    """Real or counterfactual conditions for one trap, parsed from the committed
    `task-075-t03-forensic-trace-raw.json` -- the same source `TASK-079`'s own
    `_real_candidate_conditions_from_task075_raw` reads, reimplemented locally (read-only JSON
    parsing, not a code dependency on a `scripts/` module) so this test file has no import-path
    coupling to a diagnostic script.
    """
    payload = json.loads(TASK075_RAW.read_text(encoding="utf-8"))
    matches = [
        trace
        for trace in payload["trap_selection_traces"]
        if trace["trap_id"] == trap_id and trace["is_counterfactual"] is counterfactual
    ]
    if label_prefix is not None:
        matches = [m for m in matches if m["label"].startswith(label_prefix)]
    assert matches, f"no trace for {trap_id} (counterfactual={counterfactual}) in {TASK075_RAW}"
    return [_parse_condition_token(token) for token in matches[0]["condition"]]


def _run_one(
    dataset_root: Path,
    conditions: list[dict[str, Any]],
    outcome: Any,
    dataset_version: str,
    outcome_definition_version: str,
    label: str,
) -> CandidateValidation:
    with tempfile.TemporaryDirectory() as td:
        tmp_dir = Path(td)
        candidates_path = tmp_dir / "candidates.json"
        metrics_path = tmp_dir / "metrics.json"
        candidates_path.write_text(
            json.dumps(
                {
                    "status": "PERSISTED",
                    "outcome": {
                        "outcome_id": outcome.outcome_id,
                        "outcome_definition_version": outcome_definition_version,
                    },
                    "candidates": [
                        {
                            "candidate_id": label,
                            "conditions": conditions,
                            "outcome": outcome.outcome_id,
                        }
                    ],
                }
            ),
            encoding="utf-8",
        )
        metrics_path.write_text(json.dumps({"evaluated_hypotheses": 33_085}), encoding="utf-8")
        results, _ = run_validation(
            dataset_root=dataset_root,
            candidates_path=candidates_path,
            outcome=outcome,
            dataset_version=dataset_version,
            outcome_definition_version=outcome_definition_version,
            analysis_run_id=f"g16-regression-{label}",
            metrics_path=metrics_path,
        )
        return results[0]


