"""CODE_REVIEWER independent verification (ADR-090, TASK-087 review, mandate check 1): does null
handling in `rule_expr`'s boolean mask create a hidden population divergence between the predicted
side (development+validation) and the realized side (future_holdout) of the proposed calibration
check, on the real dataset?

**Why this matters.** `rule_expr(conditions)` (`apply.py`) builds a boolean Polars expression from
`==`/`>=`/`<` comparisons. When a condition's own feature is null for a row, Polars' three-valued
boolean logic makes the mask value null for that row (not `False`) — and `frame.filter(mask)` drops
null-mask rows from BOTH `mask` and `~mask` (neither `exposed` nor `comparison` receives them). This
means the *effective* population a rule condition selects, in practice, is not exactly "rows where
the condition holds" but "rows where the condition holds AND the condition's own feature is
non-null." If a `DECISION_TIME` feature's null rate differs meaningfully between
development+validation and future_holdout, the predicted-side and realized-side populations, though
generated by the textually identical mask-generating rule (matching TASK-087's design doc Sec 2's
own claim), would silently draw from different underlying eligible populations across the two
windows — a subtle divergence the design doc's Check 1 code trace (Sec 2) does not itself address,
since it only confirms the mask-slicing discipline, not null-handling parity.

**Result of this probe:** zero nulls across every `DECISION_TIME` feature, in every split, for the
real `travel-bookings-analytical-v1.1.0` dataset — this specific divergence channel does not
materialize in the data this project actually validates against today. Reported as a real,
independently-verified finding (a clean pass), not assumed.

Read-only. Does not modify apply.py, engine.py, or any dataset/gate/metric code.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPOSITORY / "packages/analytics/src"))
sys.path.insert(0, str(REPOSITORY / "packages/schemas/src"))

import polars as pl  # noqa: E402

DATASET_V110 = REPOSITORY / "synthetic_data/analytical/travel-bookings-analytical-v1.1.0"
OUT_PATH = REPOSITORY / "docs/benchmark/task-087-review-check1-null-divergence-raw.json"


def main() -> None:
    manifest = json.loads((DATASET_V110 / "manifest.json").read_text(encoding="utf-8"))
    features = pl.read_csv(DATASET_V110 / "features.csv", try_parse_dates=False)
    outcomes = pl.read_csv(DATASET_V110 / "outcomes.csv", try_parse_dates=False)
    metadata = pl.read_csv(DATASET_V110 / "metadata.csv", try_parse_dates=False)
    frame = pl.concat([features, outcomes, metadata.select("split_label")], how="horizontal")

    timing = manifest["feature_timing"]
    decision_time_cols = [
        c for c in features.columns if timing.get(c, {}).get("classification") == "DECISION_TIME"
    ]
    decision_time_cols = [c for c in decision_time_cols if c not in {"booking_date", "travel_date"}]

    split_sizes = {
        row["split_label"]: row["len"]
        for row in frame.group_by("split_label").len().to_dicts()
    }

    null_findings: dict[str, list[dict[str, object]]] = {}
    for col in decision_time_cols:
        by_split = frame.group_by("split_label").agg(
            pl.col(col).is_null().sum().alias("nulls"), pl.len().alias("n")
        )
        rows = by_split.to_dicts()
        if any(r["nulls"] > 0 for r in rows):
            null_findings[col] = rows

    result = {
        "task": "TASK-087",
        "review_check": 1,
        "claim_tested": (
            "Null handling in rule_expr's boolean mask does not create a hidden population "
            "divergence (different effective eligible population) between the predicted side "
            "(development+validation) and realized side (future_holdout) for any DECISION_TIME "
            "feature in the real dataset."
        ),
        "dataset": "travel-bookings-analytical-v1.1.0",
        "decision_time_features_checked": decision_time_cols,
        "split_sizes": split_sizes,
        "features_with_any_null_by_split": null_findings,
        "zero_null_divergence_confirmed": not null_findings,
        "interpretation": (
            "Zero nulls found in any DECISION_TIME feature, in any split, for the real dataset this "
            "project validates against today. The theoretical null-handling divergence channel this "
            "probe checks for does not materialize here -- Check 1's 'identical population masks on "
            "both sides' claim is independently confirmed clean, not merely by the design doc's own "
            "mask-slicing code trace (which does not itself address null-handling parity) but by "
            "direct inspection of the actual data. This is dataset-contingent, not an "
            "architectural guarantee: a future dataset version with nulls in a DECISION_TIME feature "
            "would need this check re-run."
        ),
    }
    print(json.dumps(result, indent=2))
    OUT_PATH.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(f"\nWrote {OUT_PATH}", file=sys.stderr)


if __name__ == "__main__":
    main()
